"""Helper (Claude): build runs/PAPER_TABLES_cifar100.md (same format as the CIFAR-10 file) plus a pooled
CIFAR-10 + CIFAR-100 paired analysis and the tier-4c keep-easy comparison. Read-only on runs/*/results."""
import glob
import json
import os
from pathlib import Path

import numpy as np
import pandas as pd

R = Path("runs")
RATIOS = [0.3, 0.5, 0.7]
INF = "pair_influence@dinov2_s14[influence_key=param_norm_e10]"
EASY = "pair_influence@dinov2_s14[influence_key=param_norm_e10,keep=easy]"
RND = "pair_random@dinov2_s14"
LOSS = "pair_loss@dinov2_s14[loss_key=loss_e10]"


def load(run):
    rows = [json.load(open(f)) for f in glob.glob(str(R / run / "results" / "*.json"))]
    d = pd.DataFrame(rows)
    for m in ("val_acc", "test_acc", "val_b_acc"):
        if m in d:
            d[m] = d[m] * 100
    return d


def score_hours(run, seeds):
    h = 0.0
    for s in seeds:
        f = R / run / f"seed{s}" / "score" / "meta.json"
        if f.exists():
            m = json.load(open(f))
            h += (m.get("train_time_s", 0) + m.get("score_time_s", 0) + (m.get("rescore_time_s", 0) or 0)) / 3600
    return h


def ms(x):
    x = x.dropna()
    if len(x) == 0:
        return ""
    if len(x) == 1:
        return f"{x.iloc[0]:.2f}"
    return f"{x.mean():.2f} ± {x.std(ddof=1):.2f}"


def table(d, names, metric, ratios, nseeds=True):
    lines = ["| method | " + " | ".join(f"{int(r*100)}%" for r in ratios) + (" | n |" if nseeds else " |"),
             "|---" * (len(ratios) + 1 + nseeds) + "|"]
    for tag, label in names:
        cells, ns = [], set()
        for r in ratios:
            x = d[(d.tag == tag) & (np.isclose(d.ratio, r))][metric]
            cells.append(ms(x)); ns.add(len(x.dropna()))
        lines.append(f"| {label} | " + " | ".join(cells) + (f" | {'/'.join(map(str, sorted(ns)))} |" if nseeds else " |"))
    return "\n".join(lines)


def paired(d, a, b, metric):
    """Long frame of (ratio, seed, diff = a - b) for cells where both exist."""
    p = d[d.tag.isin([a, b])].pivot_table(index=["ratio", "seed"], columns="tag", values=metric)
    if a not in p or b not in p:
        return pd.DataFrame(columns=["ratio", "seed", "diff"])
    return (p[a] - p[b]).dropna().rename("diff").reset_index()


def diff_table(d, pairs, metric, ratios):
    out = ["| comparison | ratio | seed 0 | seed 1 | seed 2 | mean ± std |", "|---|---|---|---|---|---|"]
    for a, b, lab in pairs:
        x = paired(d, a, b, metric)
        for r in ratios:
            xr = x[np.isclose(x.ratio, r)].set_index("seed")["diff"]
            if len(xr) == 0:
                continue
            sd = f"{xr.std(ddof=1):.2f}" if len(xr) > 1 else "–"
            out.append(f"| {lab} | {int(r*100)}% | " + " | ".join(
                f"{xr[s]:+.2f}" if s in xr.index else "" for s in (0, 1, 2)) + f" | {xr.mean():+.2f} ± {sd} |")
    return "\n".join(out)


def cluster_boot(df, n=10000, seed=0):
    """Mean and percentile 95% CI, resampling whole scoring runs (dataset x seed) with replacement, so the
    ratios that share one scoring run stay together. Returns (mean, lo, hi)."""
    rng = np.random.default_rng(seed)
    groups = [g["diff"].to_numpy() for _, g in df.groupby(["dataset", "seed"])]
    k = len(groups)
    stats = np.empty(n)
    for i in range(n):
        pick = rng.integers(0, k, k)
        stats[i] = np.concatenate([groups[j] for j in pick]).mean()
    return df["diff"].mean(), *np.percentile(stats, [2.5, 97.5])


out = []
P = out.append
P("# CIFAR-100 paper tables (frozen study)\n")
P("_Generated by `make_paper_tables_c100.py` (Claude's helper) from `runs/*/results/*.json`. Mean ± sample std over "
  "seeds; accuracies in %. Model: ResNet-18, 100 epochs, pool 45,000, val 5,000. Influence on the 51,300-parameter "
  "head uses K-FAC. Seed 0 ran on the GTX 1080, seeds 1–2 on Kaggle T4._\n")

# ---- Tier 4
t4 = load("cifar100_r18_snap")
T4 = [("random", "random"), ("el2n", "el2n"), ("ccs", "ccs"),
      ("pair_random@self", "pair_random (self)"), ("pair_influence@self", "pair_influence (self)"),
      (RND, "pair_random (DINOv2)"), (INF, "pair_influence (DINOv2, e10 scores)"),
      (LOSS, "pair_loss (DINOv2, e10 loss)")]
P("## 1. Tier 4 — CIFAR-100 confirmation (`runs/cifar100_r18_snap`, seeds 0–2)\n")
for m in ("test_acc", "val_acc"):
    P(f"### {m}\n")
    P(table(t4, [("full", "full data")], m, [0.0]) + "\n")
    P(table(t4, T4, m, RATIOS) + "\n")

P("### Paired differences on the same DINOv2 pairs (pair_influence[e10] minus control), per seed\n")
for m in ("val_acc", "test_acc"):
    P(f"**{m}**\n")
    P(diff_table(t4, [(INF, RND, "pair_random (DINOv2)"), (INF, LOSS, "pair_loss (DINOv2, e10 loss)")], m, RATIOS) + "\n")

# ---- Tier 4c (keep easy), both datasets
t2c = load("cifar10_r18_snap")
P("## 2. Tier 4c — keep the easier twin (`pair_influence[keep=easy]`, DINOv2 pairs, e10 scores)\n")
P("_Prediction stated in the YAML before running (Sorscher et al. 2022): at high pruning ratios keep-easy beats "
  "keep-hard. Keep-hard = the existing pair_influence[e10] runs on the same scoring runs and pairs._\n")
for ds, d in (("CIFAR-10 (`runs/cifar10_r18_snap`)", t2c), ("CIFAR-100 (`runs/cifar100_r18_snap`)", t4)):
    P(f"### {ds}\n")
    if (d.tag == EASY).sum() == 0:
        P("_Not run yet._\n")
        continue
    for m in ("val_acc", "test_acc"):
        P(f"**{m}**\n")
        P(table(d, [(INF, "keep hard (pair_influence e10)"), (EASY, "keep easy"), (RND, "pair_random (DINOv2)")],
                m, [0.5, 0.7]) + "\n")
        P(diff_table(d, [(EASY, INF, "keep easy − keep hard"), (EASY, RND, "keep easy − pair_random")], m, [0.5, 0.7]) + "\n")

# ---- Pooled analysis
P("## 3. Pooled CIFAR-10 + CIFAR-100 analysis (val_acc, DINOv2 pairs, pair_influence[e10] minus control)\n")
P("_CIFAR-10 cells from tier 2c (`runs/cifar10_r18_snap`), CIFAR-100 cells from tier 4. 95% CI: percentile "
  "bootstrap, 10,000 resamples, resampling whole scoring runs (dataset × seed; 6 clusters) so that the ratios "
  "sharing one scoring run stay together. With only 6 clusters the bootstrap CI is narrower than an exact "
  "interval would be; read it as descriptive._\n")
long = []
for ds, d in (("CIFAR-10", t2c), ("CIFAR-100", t4)):
    for ctl, lab in ((RND, "pair_random"), (LOSS, "pair_loss")):
        x = paired(d, INF, ctl, "val_acc")
        x = x[[any(np.isclose(r, q) for q in RATIOS) for r in x.ratio]].copy()
        x["dataset"], x["control"] = ds, lab
        long.append(x)
long = pd.concat(long, ignore_index=True)
for lab in ("pair_random", "pair_loss"):
    x = long[long.control == lab]
    P(f"### vs {lab}\n")
    P("| dataset | ratio | seed 0 | seed 1 | seed 2 |\n|---|---|---|---|---|")
    for ds in ("CIFAR-10", "CIFAR-100"):
        for r in RATIOS:
            xr = x[(x.dataset == ds) & np.isclose(x.ratio, r)].set_index("seed")["diff"]
            P(f"| {ds} | {int(r*100)}% | " + " | ".join(f"{xr[s]:+.2f}" if s in xr.index else "" for s in (0, 1, 2)) + " |")
    P("")
    P("| ratio | n | positive | mean | 95% CI |\n|---|---|---|---|---|")
    for r in RATIOS:
        xr = x[np.isclose(x.ratio, r)]
        mu, lo, hi = cluster_boot(xr)
        P(f"| {int(r*100)}% | {len(xr)} | {(xr['diff'] > 0).sum()}/{len(xr)} | {mu:+.2f} | [{lo:+.2f}, {hi:+.2f}] |")
    mu, lo, hi = cluster_boot(x)
    P(f"| **all ratios** | {len(x)} | {(x['diff'] > 0).sum()}/{len(x)} | **{mu:+.2f}** | [{lo:+.2f}, {hi:+.2f}] |\n")
long.sort_values(["control", "dataset", "ratio", "seed"]).to_csv(R / "pooled_paired_diffs_val.csv", index=False)
P("_All differences: `runs/pooled_paired_diffs_val.csv`._\n")

# ---- Diagnosis
P("## 4. Diagnosis (`dpif.diagnose`, seed 0)\n")
cols = []
for run, pre in (("cifar100_r18_snap", "C100"), ("cifar10_r18_snap", "C10")):
    f = R / run / "seed0" / "diagnosis.json"
    if f.exists():
        for k, v in json.load(open(f)).items():
            cols.append((f"{pre} {k}", v))
keys = list(cols[0][1].keys())
P("| metric | " + " | ".join(c[0] for c in cols) + " |\n" + "|---" * (len(cols) + 1) + "|")
for k in keys:
    P(f"| {k} | " + " | ".join(f"{c[1].get(k, float('nan')):.4f}" for c in cols) + " |")
P("\n_nc1 = within/between-class feature variance; pixel ratio = pixel distance of matched pairs / random same-class "
  "pairs; rho/agree = Spearman and same-victim agreement between influence and loss. CIFAR-10 columns repeated "
  "from the CIFAR-10 file for comparison._\n")

# ---- GPU hours
P("## 5. GPU-hours per tier\n")
P("| tier | run dir | seeds | scoring h | pruned-training h | total h | hardware |\n|---|---|---|---|---|---|---|")


def hrs(d, mask):
    return (d[mask].train_time_s.sum() + d[mask].select_time_s.fillna(0).sum()) / 3600


t4_main = (t4.tag != "full") & (t4.tag != EASY)
rows = [("4 seed 0", "cifar100_r18_snap", t4, t4_main & (t4.seed == 0), [0], "GTX 1080"),
        ("4 seeds 1–2", "cifar100_r18_snap", t4, t4_main & (t4.seed > 0), [1, 2], "Kaggle T4")]
if (t4.tag == EASY).any():
    rows.append(("4c (CIFAR-100)", "cifar100_r18_snap", t4, t4.tag == EASY, [], "GTX 1080"))
if (t2c.tag == EASY).any():
    rows.append(("4c (CIFAR-10)", "cifar10_r18_snap", t2c, t2c.tag == EASY, [], "GTX 1080"))
tot = 0
for name, run, d, mask, seeds, hw in rows:
    sh = score_hours(run, seeds)
    th = hrs(d, mask)
    tot += sh + th
    P(f"| {name} | {run} | {','.join(map(str, seeds)) or '– (reused)'} | {sh:.2f} | {th:.2f} | {sh + th:.2f} | {hw} |")
P(f"| **total** | | | | | **{tot:.2f}** | |\n")
P("_Scoring h = full-data training + influence + rescore (TracIn) from score/meta.json. Seed 0 includes a ~1 h "
  "slowdown of unknown cause on 19 Nov. Kaggle T4 times are not comparable with the GTX 1080._\n")

tmp = R / "PAPER_TABLES_cifar100.md.tmp"
tmp.write_text("\n".join(out), encoding="utf-8")
os.replace(tmp, R / "PAPER_TABLES_cifar100.md")
print("wrote", R / "PAPER_TABLES_cifar100.md")
