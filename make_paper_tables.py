"""Helper (Claude): build runs/PAPER_TABLES_cifar10.md from the frozen CIFAR-10 runs. Read-only on runs/*/results."""
import glob
import json
import os
from pathlib import Path

import numpy as np
import pandas as pd

R = Path("runs")


def load(run):
    rows = [json.load(open(f)) for f in glob.glob(str(R / run / "results" / "*.json"))]
    d = pd.DataFrame(rows)
    for m in ("val_acc", "test_acc", "val_b_acc"):
        if m in d:
            d[m] = d[m] * 100
    return d


def score_hours(run, seeds):
    h = 0.0
    for s in seeds:
        f = R / run / f"seed{s}" / "score" / "meta.json"
        if f.exists():
            m = json.load(open(f))
            h += (m.get("train_time_s", 0) + m.get("score_time_s", 0) + m.get("rescore_time_s", 0) or 0) / 3600
    return h


def ms(x):
    x = x.dropna()
    if len(x) == 0:
        return ""
    if len(x) == 1:
        return f"{x.iloc[0]:.2f}"
    return f"{x.mean():.2f} ± {x.std(ddof=1):.2f}"


def table(d, names, metric, ratios, nseeds=True):
    lines = ["| method | " + " | ".join(f"{int(r*100)}%" for r in ratios) + (" | n |" if nseeds else " |"),
             "|---" * (len(ratios) + 1 + nseeds) + "|"]
    for tag, label in names:
        cells, ns = [], set()
        for r in ratios:
            x = d[(d.tag == tag) & (np.isclose(d.ratio, r))][metric]
            cells.append(ms(x)); ns.add(len(x.dropna()))
        lines.append(f"| {label} | " + " | ".join(cells) + (f" | {'/'.join(map(str, sorted(ns)))} |" if nseeds else " |"))
    return "\n".join(lines)


out = []
P = out.append
P("# CIFAR-10 paper tables (frozen study)\n")
P("_Generated by `make_paper_tables.py` (Claude's helper) from `runs/*/results/*.json`. Mean ± sample std over seeds; "
  "accuracies in %. Model: ResNet-18, 100 epochs, pool 45,000, val 5,000 (val_b = held-out half B, 2,500)._\n")

# ---- Tier 2
t2 = load("cifar10_r18")
T2 = [("full", "full data"), ("random", "random"), ("el2n", "el2n"), ("ccs", "ccs"), ("moderate", "moderate"),
      ("pair_random@self", "pair_random (self)"), ("pair_influence@self", "pair_influence (self)"),
      ("pair_loss@self", "pair_loss (self)"), ("pair_influence_rw@self", "pair_influence_rw (self)")]
P("## 1. Tier 2 — headline methods (`runs/cifar10_r18`, seeds 0–2)\n")
for m in ("test_acc", "val_acc"):
    P(f"### {m}\n")
    P(table(t2, T2[:1], m, [0.0]) + "\n")
    P(table(t2, T2[1:], m, [0.3, 0.5, 0.7]) + "\n")

# ---- Tier 2c
t2c = load("cifar10_r18_snap")
C = [("pair_random@dinov2_s14", "pair_random (DINOv2)"),
     ("pair_influence@dinov2_s14[influence_key=param_norm_e10]", "pair_influence (DINOv2, e10 scores)"),
     ("pair_loss@dinov2_s14[loss_key=loss_e10]", "pair_loss (DINOv2, e10 loss)"),
     ("pair_influence@self_e10[influence_key=param_norm_e10]", "pair_influence (self_e10 pairs, e10 scores)")]
P("## 2. Tier 2c — confirmation (`runs/cifar10_r18_snap`, seeds 0–2)\n")
P("_Separate scoring runs from tier 2 (same seeds, with epoch-10/30 snapshots). Seed 0 at 50/70% comes from the "
  "tier-2b/2b+ runs, same run directory and recipe._\n")
for m in ("test_acc", "val_acc"):
    P(f"### {m}\n")
    P(table(t2c, [("full", "full data (snapshot scoring runs)")], m, [0.0]) + "\n")
    P(table(t2c, C, m, [0.3, 0.5, 0.7]) + "\n")

P("### Paired differences on the same DINOv2 pairs (pair_influence[e10] minus control), per seed\n")
for m in ("val_acc", "test_acc"):
    p = t2c[t2c.tag.isin([c[0] for c in C[:3]])].pivot_table(index=["ratio", "seed"], columns="tag", values=m)
    P(f"**{m}**\n")
    P("| control | ratio | seed 0 | seed 1 | seed 2 | mean ± std |\n|---|---|---|---|---|---|")
    for ctl, lab in (C[0], C[2]):
        for r in (0.3, 0.5, 0.7):
            x = (p[C[1][0]] - p[ctl]).xs(r, level="ratio")
            P(f"| {lab} | {int(r*100)}% | " + " | ".join(f"{x.get(s, np.nan):+.2f}" for s in (0, 1, 2))
              + f" | {x.mean():+.2f} ± {x.std(ddof=1):.2f} |")
    P("")

# ---- Tier 2d
t2d = load("cifar10_r18_dir")
D = [("pair_random@dinov2_s14", "pair_random"),
     ("pair_loss@dinov2_s14[loss_key=loss_e10]", "pair_loss, e10 loss (reference)"),
     ("pair_influence@dinov2_s14[influence_key=param_norm_e10]", "pair_influence, e10 (reference)"),
     ("pair_valinf@dinov2_s14[valinf_key=val_removal_A_e10]", "pair_valinf, val-A IF, e10"),
     ("pair_valinf@dinov2_s14[valinf_key=val_removal_A]", "pair_valinf, val-A IF, final"),
     ("pair_loss@dinov2_s14[loss_key=tracin_val_early]", "TracIn to val-A, epochs ≤ 20"),
     ("pair_loss@dinov2_s14[loss_key=tracin_val]", "TracIn to val-A, all checkpoints")]
P("## 3. Tier 2d — validation-directed influence (`runs/cifar10_r18_dir`, seed 0, DINOv2 pairs)\n")
P("_Directed scores use val half A, so methods are judged on val_b_acc only. Single seed._\n")
for m in ("val_b_acc", "test_acc"):
    P(f"### {m}\n")
    P(table(t2d, [("full", "full data")], m, [0.0], nseeds=False) + "\n")
    P(table(t2d, D, m, [0.5, 0.7], nseeds=False) + "\n")

# ---- Exploratory
P("## 4. Exploratory (not for headline claims)\n")
t1 = load("cifar10_t1")
P("### Tier 1 — `runs/cifar10_t1`: 1 seed, **30 epochs**, influence numerics before v2\n")
tags1 = sorted(t1.tag.unique(), key=lambda t: (t != "full", t))
for m in ("val_acc", "test_acc"):
    P(f"**{m}**\n")
    P(table(t1, [("full", "full data")], m, [0.0], nseeds=False) + "\n")
    P(table(t1, [(t, t) for t in tags1 if t != "full"], m, [0.3, 0.5, 0.7], nseeds=False) + "\n")
P("### Tier 2b / 2b+ — `runs/cifar10_r18_snap`, seed 0, 50/70% (methods not carried into tier 2c)\n")
s0 = t2c[t2c.seed == 0]
EASY = "pair_influence@dinov2_s14[influence_key=param_norm_e10,keep=easy]"  # tier 4c, reported in PAPER_TABLES_cifar100.md
tags2b = sorted(set(s0.tag) - {"full", EASY} - {c[0] for c in C})
for m in ("val_acc", "test_acc"):
    P(f"**{m}**\n")
    P(table(s0, [(t, t) for t in tags2b], m, [0.5, 0.7], nseeds=False) + "\n")

# ---- Diagnosis
P("## 5. Diagnosis (`dpif.diagnose`, seed 0)\n")
cols = []
for run, lab in (("cifar10_t1", "tier 1 final (30 ep)"), ("cifar10_r18", "tier 2 final"),
                 ("cifar10_r18_snap", None)):
    f = R / run / "seed0" / "diagnosis.json"
    if f.exists():
        dj = json.load(open(f))
        for k, v in dj.items():
            cols.append((lab if lab else f"snap {k}", v))
keys = list(cols[0][1].keys())
P("| metric | " + " | ".join(c[0] for c in cols) + " |\n|---" * 1 + "|---" * len(cols) + "|")
for k in keys:
    P(f"| {k} | " + " | ".join(f"{c[1].get(k, float('nan')):.4f}" for c in cols) + " |")
P("\n_nc1 = within/between-class feature variance; pixel ratio = pixel distance of matched pairs / random same-class "
  "pairs; rho/agree = Spearman and same-victim agreement between influence and loss._\n")

# ---- GPU hours
P("## 6. GPU-hours per tier\n")
P("| tier | run dir | seeds | scoring h | pruned-training h | total h | hardware |\n|---|---|---|---|---|---|---|")


def hrs(d, mask):
    return (d[mask].train_time_s.sum() + d[mask].get("select_time_s", pd.Series(dtype=float)).fillna(0)[mask].sum()) / 3600


nonfull = lambda d: d.tag != "full"
rows = [("1 (decision)", "cifar10_t1", t1, nonfull(t1), [0], "GTX 1080"),
        ("2 seed 0", "cifar10_r18", t2, nonfull(t2) & (t2.seed == 0), [0], "GTX 1080"),
        ("2 seeds 1–2", "cifar10_r18", t2, nonfull(t2) & (t2.seed > 0), [1, 2], "Kaggle T4"),
        ("2d", "cifar10_r18_dir", t2d, nonfull(t2d), [0], "GTX 1080")]
tier2b = {"pair_random@self_e10", "pair_influence@self_e10[influence_key=param_norm_e10]",
          "pair_loss@self_e10[loss_key=loss_e10]", "pair_random@dinov2_s14",
          "pair_influence@dinov2_s14[influence_key=param_norm_e10]"}
tier2bp = {"pair_loss@dinov2_s14[loss_key=loss_e10]", "pair_loss@dinov2_s14[loss_key=el2n]", "pair_influence@dinov2_s14"}
base = nonfull(t2c) & (t2c.seed == 0) & np.isclose(t2c.ratio, 0.5) | nonfull(t2c) & (t2c.seed == 0) & np.isclose(t2c.ratio, 0.7)
m2b = base & t2c.tag.isin(tier2b)
m2bp = base & t2c.tag.isin(tier2bp)
m2c = nonfull(t2c) & ~m2b & ~m2bp & (t2c.tag != EASY)
rows[3:3] = [("2b", "cifar10_r18_snap", t2c, m2b, [0], "GTX 1080"),
             ("2b+", "cifar10_r18_snap", t2c, m2bp, [], "GTX 1080"),
             ("2c", "cifar10_r18_snap", t2c, m2c, [1, 2], "GTX 1080")]
tot = 0
for name, run, d, mask, seeds, hw in rows:
    sh = score_hours(run, seeds)
    th = hrs(d, mask)
    tot += sh + th
    P(f"| {name} | {run} | {','.join(map(str, seeds)) or '–'} | {sh:.2f} | {th:.2f} | {sh + th:.2f} | {hw} |")
P(f"| **total** | | | | | **{tot:.2f}** | |\n")
P("_Scoring h = full-data training + influence (+ rescore when recorded) from score/meta.json. Times on the GTX 1080 "
  "include slowdowns while the GPU was shared with a game; Kaggle T4 times are not comparable._\n")

tmp = R / "PAPER_TABLES_cifar10.md.tmp"
tmp.write_text("\n".join(out), encoding="utf-8")
os.replace(tmp, R / "PAPER_TABLES_cifar10.md")
print("wrote", R / "PAPER_TABLES_cifar10.md")
